// Writes demo/public/tor-client/fallbacks.js, the addresses of the fallback
// directories arti has compiled in, from the tor-dircommon crate that the
// tor-js release in package.json was built with (docs/tor-over-wisp.md
// "Which relays the worker may reach"). Before the client has a consensus,
// these are the only addresses its Wisp streams may go to.
//
// 1. The crate's version and checksum are in tor-js's Cargo.lock at the
//    release's commit (`gitHead` of `npm view tor-js@<version>`):
//      gh api "repos/ethereum/tor-js/contents/Cargo.lock?ref=<gitHead>" \
//        --jq .content | base64 -d | grep -A3 'name = "tor-dircommon"'
// 2. curl -sSfLO https://static.crates.io/crates/tor-dircommon/tor-dircommon-<v>.crate
//    sha256sum it against the checksum, and untar it in an empty directory.
// 3. node scripts/tor-fallbacks.mjs <dir>/data/fallback_dirs.rs <v> <checksum>
import { readFileSync, writeFileSync } from 'node:fs';

const [source, version, checksum] = process.argv.slice(2);
if (!source || !version || !checksum) {
	console.error(
		'usage: node scripts/tor-fallbacks.mjs <fallback_dirs.rs> <version> <checksum>',
	);
	process.exit(1);
}
const text = readFileSync(source, 'utf8');
const addresses = [
	...new Set(
		[
			...text.matchAll(
				/"((?:\d{1,3}\.){3}\d{1,3}:\d+|\[[0-9a-fA-F:]+\]:\d+)"/g,
			),
		].map((match) => match[1].toLowerCase()),
	),
].sort();
if (addresses.length < 50) {
	console.error(`only ${addresses.length} addresses in ${source}`);
	process.exit(1);
}
const out = new URL('../demo/public/tor-client/fallbacks.js', import.meta.url);
writeFileSync(
	out,
	`// Generated by scripts/tor-fallbacks.mjs from tor-dircommon ${version},
// data/fallback_dirs.rs: the ORPorts of the fallback directories arti has
// compiled in. Do not edit. The crate's sha256:
// ${checksum}
export const FALLBACK_ADDRESSES = ${JSON.stringify(addresses, null, '\t')};
`,
);
console.log(`${addresses.length} addresses written to ${out.pathname}`);
